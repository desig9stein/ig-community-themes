// Generates the Angular preview's theme bundles from designs/ and registers them in angular.json.
// Each design + variant becomes a lazily loaded stylesheet built through the real Angular Sass API:
//   theme($palette, $schema: <design schema>) — exactly what an Angular app using the design would write.
import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { BASES, listDesigns, readManifest } from './design.mjs';

const APP = 'apps/angular';

// The app consumes this repo as the published package would be consumed: `@use 'igniteui-community-themes/<slug>'`.
// npm refuses to `file:`-link a package into its own subfolder, so link it here.
const link = join(APP, 'node_modules/igniteui-community-themes');
if (!existsSync(link)) {
  symlinkSync(relative(dirname(resolve(link)), resolve('.')), link, 'dir');
}
const THEMES = join(APP, 'src/themes');
rmSync(THEMES, { recursive: true, force: true });
mkdirSync(THEMES, { recursive: true });

const bundles = [];
const designs = listDesigns().map((slug) => ({ slug, ...readManifest(slug) }));

for (const d of designs) {
  for (const variant of d.variants) {
    const name = `design-${d.slug}-${variant}`;
    writeFileSync(
      join(THEMES, `${name}.scss`),
      `// Generated by scripts/angular-themes.mjs — this is the snippet an Angular app writes to use "${d.name}".
@use 'igniteui-angular/theming' as *;
@use 'igniteui-community-themes/${d.slug}' as ds;

@include core();
@include typography($font-family: ds.$${d.slug}-typeface, $type-scale: ds.$${d.slug}-type-scale);
@include theme(
    ds.$${d.slug}-${variant}-palette,
    $schema: ds.$${variant}-${d.slug}-schema,
    $elevations: ds.$${d.slug}-elevations,
    $roundness: ds.$${d.slug}-roundness
);
`,
    );
    bundles.push(name);
  }
}

// Plain built-in themes, for the "Show base only" comparison.
for (const base of BASES) {
  for (const variant of ['light', 'dark']) {
    const name = `base-${base}-${variant}`;
    const elevations = base === 'indigo' ? '$indigo-elevations' : '$material-elevations';
    writeFileSync(
      join(THEMES, `${name}.scss`),
      `// Generated by scripts/angular-themes.mjs — the built-in ${base} ${variant} theme.
@use 'igniteui-angular/theming' as *;

@include core();
@include typography($font-family: $${base}-typeface, $type-scale: $${base}-type-scale);
@include theme($${variant}-${base}-palette, $schema: $${variant}-${base}-schema, $elevations: ${elevations});
`,
    );
    bundles.push(name);
  }
}

const configPath = join(APP, 'angular.json');
const config = JSON.parse(readFileSync(configPath, 'utf8'));
const project = Object.values(config.projects)[0];
project.architect.build.options.styles = [
  'src/styles.scss',
  ...bundles.map((b) => ({ input: `src/themes/${b}.scss`, bundleName: b, inject: false })),
];
writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);

writeFileSync(
  join(APP, 'src/app/designs.generated.ts'),
  `// Generated by scripts/angular-themes.mjs from designs/*/manifest.json.
export interface DesignInfo { slug: string; name: string; base: string; variants: string[]; maintainers: string[]; fonts?: string[]; }
export const DESIGNS: DesignInfo[] = ${JSON.stringify(
    designs.map(({ slug, name, base, variants, maintainers, fonts }) => ({ slug, name, base, variants, maintainers, fonts })),
    null,
    2,
  )};
`,
);

console.log(`✓ ${bundles.length} Angular theme bundles`);
