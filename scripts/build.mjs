// Compiles every design in designs/ to dist/<slug>/<variant>.css and writes dist/index.json + .github/CODEOWNERS.
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { listDesigns, readManifest, checkManifest, compile, paletteColors } from './design.mjs';

const DIST = 'dist';
rmSync(DIST, { recursive: true, force: true });

const index = [];
let failed = false;

for (const slug of listDesigns()) {
  const manifest = readManifest(slug);
  const errors = checkManifest(slug, manifest);
  if (errors.length) {
    console.error(`✗ ${slug}\n  ${errors.join('\n  ')}`);
    failed = true;
    continue;
  }

  mkdirSync(join(DIST, slug), { recursive: true });
  const swatches = {};

  try {
    for (const variant of manifest.variants) {
      const { css } = compile(slug, manifest, variant);
      writeFileSync(join(DIST, slug, `${variant}.css`), css);
      const c = paletteColors(slug, variant);
      swatches[variant] = Object.fromEntries(
        Object.entries(c).map(([k, rgb]) => [k.split(' ')[0], `rgb(${rgb.map(Math.round).join(' ')})`]),
      );
    }
  } catch (e) {
    console.error(`✗ ${slug}\n  ${e.message}`);
    failed = true;
    continue;
  }

  const { $schema, ...meta } = manifest;
  index.push({ ...meta, swatches });
  console.log(`✓ ${slug} (${manifest.variants.join(', ')})`);
}

writeFileSync(join(DIST, 'index.json'), JSON.stringify(index, null, 2));

// Each design folder is owned by its maintainers, not by the repo admins.
const owners = index.map((d) => `/designs/${d.slug}/ ${d.maintainers.map((m) => `@${m}`).join(' ')}`);
mkdirSync('.github', { recursive: true });
writeFileSync(
  join('.github', 'CODEOWNERS'),
  `# Generated by scripts/build.mjs from designs/*/manifest.json. Do not edit by hand.\n* @desig9stein\n${owners.join('\n')}\n`,
);

if (failed) process.exit(1);
